import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { CaseResult, RunReport } from "./types.js";

function pad(s: string, n: number): string {
  if (s.length >= n) return s.slice(0, n - 1) + "…";
  return s + " ".repeat(n - s.length);
}

export function formatTable(results: CaseResult[]): string {
  const lines: string[] = [];
  lines.push(
    `${pad("ID", 26)} ${pad("KIND", 12)} ${pad("RESULT", 8)} ${pad("CHECKS", 10)} LATENCY`,
  );
  lines.push("-".repeat(72));
  for (const r of results) {
    const mark = r.pass ? "PASS" : "FAIL";
    const checks = `${r.checks.filter((c) => c.ok).length}/${r.checks.length}`;
    lines.push(
      `${pad(r.id, 26)} ${pad(r.kind, 12)} ${pad(mark, 8)} ${pad(checks, 10)} ${r.latencyMs}ms`,
    );
  }
  return lines.join("\n");
}

export function formatMarkdown(report: RunReport): string {
  const lines: string[] = [];
  lines.push(`# CiteBot eval report`);
  lines.push("");
  lines.push(`- **Suite:** ${report.suite}`);
  lines.push(`- **Provider:** ${report.provider}`);
  lines.push(`- **Target:** ${report.target}`);
  lines.push(`- **Started:** ${report.startedAt}`);
  lines.push(`- **Finished:** ${report.finishedAt}`);
  lines.push(
    `- **Score:** **${report.score}** (${report.passed}/${report.total} passed)`,
  );
  lines.push("");
  lines.push(`## Results`);
  lines.push("");
  lines.push(`| ID | Kind | Result | Checks | Latency |`);
  lines.push(`|----|------|--------|--------|---------|`);
  for (const r of report.results) {
    lines.push(
      `| \`${r.id}\` | ${r.kind} | ${r.pass ? "✅ PASS" : "❌ FAIL"} | ${r.checks.filter((c) => c.ok).length}/${r.checks.length} | ${r.latencyMs}ms |`,
    );
  }
  lines.push("");
  lines.push(`## Failures / notes`);
  lines.push("");
  const fails = report.results.filter((r) => !r.pass);
  if (fails.length === 0) {
    lines.push("_All cases passed._");
  } else {
    for (const r of fails) {
      lines.push(`### \`${r.id}\``);
      lines.push("");
      lines.push(`> ${r.question}`);
      lines.push("");
      for (const c of r.checks.filter((x) => !x.ok)) {
        lines.push(`- **${c.name}:** ${c.detail}`);
      }
      if (r.error) lines.push(`- **error:** ${r.error}`);
      lines.push(`- answer preview: ${r.answerPreview || "(empty)"}`);
      lines.push("");
    }
  }
  lines.push("---");
  lines.push("");
  lines.push(
    `_Generated by [citebot-evals](https://github.com/jakob-alexander2000/citebot-evals). Re-run: \`npm run eval -- --provider ${report.provider}\`._`,
  );
  return lines.join("\n");
}

export function writeReports(
  report: RunReport,
  outDir: string,
): { jsonPath: string; mdPath: string } {
  mkdirSync(outDir, { recursive: true });
  const stamp = report.finishedAt.replace(/[:.]/g, "-");
  const jsonPath = join(outDir, `run-${stamp}.json`);
  const mdPath = join(outDir, `run-${stamp}.md`);
  const latestJson = join(outDir, "latest.json");
  const latestMd = join(outDir, "latest.md");
  const body = JSON.stringify(report, null, 2);
  const md = formatMarkdown(report);
  writeFileSync(jsonPath, body);
  writeFileSync(mdPath, md);
  writeFileSync(latestJson, body);
  writeFileSync(latestMd, md);
  return { jsonPath, mdPath };
}
